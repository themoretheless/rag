#!/usr/bin/env python3
"""Own disposable DB containers only. No production RAG or database process is touched."""
import json, os, secrets, subprocess, time, uuid, sys
from pathlib import Path
from smoke_external_db_runtime import exercise

SECRETS = []
def run(args, **kwargs):
    result = subprocess.run(args, text=True, capture_output=True, **kwargs)
    if result.returncode:
        error = result.stderr
        for secret in SECRETS: error = error.replace(secret, "[redacted]")
        raise RuntimeError(error)
    return result

def main():
    subprocess.run(["cargo","build","--bin","rag-mcp"],check=True)
    suffix=uuid.uuid4().hex[:10]
    pg=f'rag-ext-pg-{suffix}'; my=f'rag-ext-my-{suffix}'
    password=secrets.token_hex(16)
    SECRETS.append(password)
    owned=[]
    try:
        for name,image,env,port in [(pg,'postgres:16-alpine',{'POSTGRES_PASSWORD':password,'POSTGRES_DB':'app'},5432),(my,'mysql:8.4',{'MYSQL_ROOT_PASSWORD':password,'MYSQL_DATABASE':'app'},3306)]:
            args=['docker','run','-d','--name',name,'--label',f'rag-fixture={suffix}','-p',f'127.0.0.1::{port}']
            for k,v in env.items(): args+=['-e',f'{k}={v}']
            run(args+[image]);owned.append(name)
        for name,probe in [(pg,['pg_isready','-U','postgres','-d','app']),(my,['mysql','--protocol=TCP','-h127.0.0.1','-uroot',f'-p{password}','-e','SELECT 1'])]:
            for _ in range(90):
                if subprocess.run(['docker','exec',name]+probe,stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL).returncode==0: break
                time.sleep(1)
            else: raise RuntimeError('fixture startup timed out')
        pg_sql=f'''CREATE TABLE parent(a INT,b INT,PRIMARY KEY(a,b));
CREATE TABLE child(a INT,b INT, note TEXT,email TEXT,"a""b" INT,computed INT GENERATED ALWAYS AS (a+b) STORED,FOREIGN KEY(a,b) REFERENCES parent(a,b));
ALTER TABLE child ADD CONSTRAINT child_unique UNIQUE(a,b) DEFERRABLE INITIALLY DEFERRED;
ALTER TABLE child ADD CONSTRAINT child_quoted_unique UNIQUE("a""b");
ALTER TABLE child ADD CONSTRAINT child_nonnegative CHECK(a>=0) NOT VALID;
CREATE INDEX child_pair ON child(b DESC,a);
CREATE INDEX child_expr ON child((lower(note))) INCLUDE(email) WHERE a IS NULL;
CREATE UNIQUE INDEX child_nulls_equal ON child(a,b) NULLS NOT DISTINCT;
ALTER TABLE child ADD COLUMN id INT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE child ADD COLUMN created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP;
ALTER TABLE child ADD COLUMN period int4range;
ALTER TABLE child ADD CONSTRAINT no_overlap EXCLUDE USING gist(period WITH &&);
CREATE VIEW child_view AS SELECT a,b,lower(note) AS note_tag FROM child WHERE a>=0 OR a IS NULL;
CREATE VIEW nested_view AS SELECT a FROM child_view;
CREATE MATERIALIZED VIEW child_mv AS SELECT b FROM child WITH NO DATA;
CREATE TABLE users(id INT PRIMARY KEY);
CREATE TABLE companies(id INT PRIMARY KEY);
CREATE TABLE accounts(id INT,tenant INT,UNIQUE(id,tenant));
CREATE TABLE events(id INT,user_id INT,"UserID" INT,"AuthorUserID" INT,company_id INT,account_id INT,report_user_id TEXT,declared_user_id INT,paid BOOLEAN,FOREIGN KEY(declared_user_id) REFERENCES users(id));
CREATE TYPE public.order_status AS ENUM ('new','in,progress','quote''d',E'slash\\\\path','done');
CREATE DOMAIN public.user_identifier AS INTEGER DEFAULT 7 NOT NULL CHECK (VALUE>0);
CREATE DOMAIN public.nested_identifier AS public.user_identifier DEFAULT 9 CHECK (VALUE<10000);
ALTER TABLE events ADD COLUMN domain_user_id public.nested_identifier;
ALTER TABLE events ADD COLUMN state public.order_status DEFAULT 'new';
ALTER TABLE events ADD COLUMN states public.order_status[];
ALTER TABLE events ADD COLUMN optional_ids public.user_identifier[];
INSERT INTO events(state,states) VALUES('in,progress',ARRAY['new','quote''d']::public.order_status[]);
CREATE TABLE "odd'name"(id INT); INSERT INTO child(a,b,note) VALUES(NULL,NULL,'PRIVATE_ROW_MARKER');
CREATE USER fixture_read PASSWORD '{password}'; GRANT CONNECT ON DATABASE app TO fixture_read; GRANT USAGE ON SCHEMA public TO fixture_read; GRANT SELECT ON ALL TABLES IN SCHEMA public TO fixture_read;'''
        my_sql=f'''USE app; CREATE TABLE parent(a INT,b INT,PRIMARY KEY(a,b));
CREATE TABLE child(a INT,b INT,note TEXT,email TEXT,`a"b` INT,computed INT GENERATED ALWAYS AS (a+b) STORED,FOREIGN KEY(a,b) REFERENCES parent(a,b));
ALTER TABLE child ADD CONSTRAINT child_unique UNIQUE(a,b);
ALTER TABLE child ADD CONSTRAINT child_quoted_unique UNIQUE(`a"b`);
ALTER TABLE child ADD CONSTRAINT child_nonnegative CHECK(a>=0) NOT ENFORCED;
CREATE INDEX child_pair ON child(b DESC,a);
CREATE INDEX child_expr ON child((CAST(lower(note) AS CHAR(24))));
CREATE INDEX child_note_prefix ON child(note(12)) INVISIBLE;
ALTER TABLE child ADD COLUMN id INT AUTO_INCREMENT, ADD INDEX child_identity(id);
ALTER TABLE child ADD COLUMN created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP;
CREATE VIEW child_view AS SELECT a,b,lower(note) AS note_tag FROM child WHERE a>=0 OR a IS NULL;
CREATE VIEW nested_view AS SELECT a FROM child_view;
CREATE TABLE users(id INT PRIMARY KEY);
CREATE TABLE companies(id INT PRIMARY KEY);
CREATE TABLE accounts(id INT,tenant INT,UNIQUE(id,tenant));
CREATE TABLE events(id INT,user_id INT,UserID INT,AuthorUserID INT,company_id INT,account_id INT,report_user_id TEXT,declared_user_id INT,paid BOOLEAN,FOREIGN KEY(declared_user_id) REFERENCES users(id));
ALTER TABLE events ADD COLUMN domain_user_id INT;
ALTER TABLE events ADD COLUMN state ENUM('new','in,progress','quote''d','slash\\\\path','done') DEFAULT 'new';
ALTER TABLE events ADD COLUMN permissions SET('read','write','quote''d','slash\\\\x');
INSERT INTO events(state,permissions) VALUES('in,progress','read,write');
CREATE TABLE `odd'name`(id INT); INSERT INTO child(a,b,note) VALUES(NULL,NULL,'PRIVATE_ROW_MARKER');
CREATE USER 'fixture_read'@'%' IDENTIFIED BY '{password}'; GRANT SELECT, SHOW VIEW ON app.* TO 'fixture_read'@'%';
CREATE USER 'fixture_limited'@'%' IDENTIFIED BY '{password}'; GRANT SELECT ON app.* TO 'fixture_limited'@'%';'''
        run(['docker','exec','-i',pg,'psql','-U','postgres','-d','app','-v','ON_ERROR_STOP=1'],input=pg_sql)
        run(['docker','exec','-i',my,'mysql','-uroot',f'-p{password}'],input=my_sql)
        env=os.environ.copy()
        for name,port,var,scheme,admin in [(pg,5432,'RAG_TEST_EXTERNAL_PG_URL','postgresql','postgres'),(my,3306,'RAG_TEST_EXTERNAL_MY_URL','mysql','root')]:
            info=json.loads(run(['docker','inspect',name]).stdout)[0]
            hostport=info['NetworkSettings']['Ports'][f'{port}/tcp'][0]['HostPort']
            env[var]=f'{scheme}://fixture_read:{password}@127.0.0.1:{hostport}/app'
            if scheme=='mysql':env[var+'_LIMITED']=f'{scheme}://fixture_limited:{password}@127.0.0.1:{hostport}/app'
            env[var+'_ADMIN']=f'{scheme}://{admin}:{password}@127.0.0.1:{hostport}/app'
        result=subprocess.run(['cargo','test','--lib','external_db::fixture_tests::','--','--ignored','--nocapture'],env=env)
        if result.returncode: raise RuntimeError('native fixture test failed')
        def mutate_schema(alias, identity_only=False, types_only=False):
            if types_only:
                if alias=='pg':
                    if types_only=='enum':sql="ALTER TYPE public.order_status ADD VALUE 'archived';"
                    else:sql="ALTER DOMAIN public.user_identifier DROP CONSTRAINT user_identifier_check; ALTER DOMAIN public.user_identifier ADD CONSTRAINT user_identifier_check CHECK(VALUE>1) NOT VALID; ALTER DOMAIN public.nested_identifier SET DEFAULT 11;"
                    run(['docker','exec','-i',pg,'psql','-U','postgres','-d','app','-v','ON_ERROR_STOP=1'],input=sql)
                else:
                    slash=chr(92)*2
                    if types_only=='enum':sql="USE app; ALTER TABLE events MODIFY state ENUM('new','in,progress','quote''d','slash"+slash+"path','done','archived') DEFAULT 'new';"
                    else:sql="USE app; ALTER TABLE events MODIFY permissions SET('read','write','quote''d','slash"+slash+"x','admin');"
                    run(['docker','exec','-i',my,'mysql','-uroot',f'-p{password}'],input=sql)
                return
            if identity_only:
                assert alias=='pg'
                run(['docker','exec','-i',pg,'psql','-U','postgres','-d','app','-v','ON_ERROR_STOP=1'],input='ALTER TABLE public.child ALTER COLUMN id SET GENERATED ALWAYS;')
                return
            if alias=='pg':
                sql="CREATE INDEX child_new_idx ON child(a DESC); ALTER TABLE child DROP CONSTRAINT child_nonnegative; ALTER TABLE child ADD CONSTRAINT child_nonnegative CHECK(a>=-1) NOT VALID; CREATE OR REPLACE VIEW child_view AS SELECT a,b,lower(note) AS note_tag FROM child WHERE a>=-1 OR a IS NULL;"
                run(['docker','exec','-i',pg,'psql','-U','postgres','-d','app','-v','ON_ERROR_STOP=1'],input=sql)
            else:
                sql="USE app; CREATE INDEX child_new_idx ON child(a DESC); ALTER TABLE child DROP CHECK child_nonnegative; ALTER TABLE child ADD CONSTRAINT child_nonnegative CHECK(a>=-1) NOT ENFORCED; CREATE OR REPLACE VIEW child_view AS SELECT a,b,lower(note) AS note_tag FROM child WHERE a>=-1 OR a IS NULL;"
                run(['docker','exec','-i',my,'mysql','-uroot',f'-p{password}'],input=sql)
        report=exercise(env, lambda:run(['docker','stop','--time','2',my]),mutate_schema)
        if len(sys.argv)>1:Path(sys.argv[1]).write_text(json.dumps(report,indent=2)+'\n')
        print('PASS: PostgreSQL 16 + MySQL 8.4, SELECT-only metadata, composite FK, generated/quoted columns, opt-in allowlisted samples, snapshot reopen, admin writes rejected by read-only transactions')
    finally:
        for name in owned:
            subprocess.run(['docker','rm','-f','-v',name],stdout=subprocess.DEVNULL,stderr=subprocess.DEVNULL)
if __name__=='__main__': main()
