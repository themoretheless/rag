#!/usr/bin/env python3
"""Capture a bounded standard SIMD type-name catalog from installed rust-src."""
import argparse
import hashlib
import json
from pathlib import Path
import re


def generate(source_root):
    specifications = {
        "arm": ["arm_shared/neon/mod.rs"],
        "aarch64": ["arm_shared/neon/mod.rs", "aarch64/neon/mod.rs"],
        "x86": ["x86/mod.rs"],
        "x86_64": ["x86/mod.rs"],
        "wasm32": ["wasm32/simd128.rs"],
    }
    files = sorted({p for paths in specifications.values() for p in paths}
                   | {"mod.rs", "macros.rs", "aarch64/mod.rs", "arm/mod.rs", "arm_shared/mod.rs", "wasm32/mod.rs"})
    captured = {name: (source_root / name).read_bytes() for name in files}
    declarations = {}
    for name, data in captured.items():
        declarations[name] = [dict(name=match.group(1), line=index)
                              for index, line in enumerate(data.decode().splitlines(), 1)
                              if (match := re.match(r"\s*pub struct ([A-Za-z_][A-Za-z0-9_]*)\b", line))]
    catalog = {module: sorted({d["name"] for path in paths for d in declarations[path]})
               for module, paths in specifications.items()}
    if any(not names for names in catalog.values()):
        raise ValueError("missing expected SIMD declarations")
    lines = ["// Generated by scripts/generate_stdarch_catalog.py; type names only.",
             "// Availability is separately constrained by captured target_arch."]
    for module, names in catalog.items():
        lines.append(f"const {module.upper()}: &[&str] = &[")
        lines.extend(f'    "{name}",' for name in names)
        lines.append("];\n")
    lines += ["pub(super) fn known(module: &str, name: &str) -> bool {",
              "    let names = match module {"]
    lines.extend(f'        "{module}" => {module.upper()},' for module in catalog)
    lines += ["        _ => return false,", "    };", "    names.binary_search(&name).is_ok()", "}"]
    provenance = dict(contract_version=1, source_root=str(source_root.resolve()), catalog=catalog,
                      source_sha256={name: hashlib.sha256(data).hexdigest() for name, data in captured.items()},
                      declarations=declarations,
                      limitations=["selected public struct names, not all stdarch items or language types",
                                   "feature/stability/compiler availability not established by the catalog",
                                   "runtime queries never read installed rust-src"])
    return "\n".join(lines) + "\n", provenance


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source_root", type=Path)
    parser.add_argument("output", type=Path)
    parser.add_argument("provenance", type=Path)
    args = parser.parse_args()
    if args.output.exists() or args.provenance.exists():
        raise ValueError("refusing to replace existing catalog or provenance")
    source, provenance = generate(args.source_root)
    with args.output.open("x") as target:
        target.write(source)
    provenance["generated_sha256"] = hashlib.sha256(source.encode()).hexdigest()
    with args.provenance.open("x") as target:
        json.dump(provenance, target, indent=2)
        target.write("\n")
    print(json.dumps({module: len(names) for module, names in provenance["catalog"].items()}))


if __name__ == "__main__":
    main()
